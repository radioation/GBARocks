//---------------------------------------------------------------------------------
// Program entry point
//---------------------------------------------------------------------------------
int main(void) {
	//---------------------------------------------------------------------------------
	// the vblank interrupt must be enabled for VBlankIntrWait() to work
	// since the default dispatcher handles the bios flags no vblank handler
	// is required
	irqInit();
	irqEnable(IRQ_VBLANK);

	// BG2_ON          =       BIT(10),        /*!< enable background 2
	// OBJ_ENABLE              =       OBJ_ON,         /*!< enable sprites     
	// OBJ_1D_MAP      =       BIT(6),         /*!< sprite 1 dimensional mapping      
	SetMode( MODE_3 | BG2_ON | OBJ_ENABLE | OBJ_1D_MAP );


	// get start of video ram
	// gba_base.h:#define      VRAM            0x06000000
	volatile u16 *vram = (volatile u16 *)VRAM;

	// set every pixel to dark blue
	for( int i=0; i < 240*160; ++i ) {
		vram[i] = RGB5( 0, 0, 4);
	}


	// set sprite palette colors. Couls also make an array and `memcpy( SPRITE_PALETTE, spritePal, spritePalLen )`;
	// gba_video.h:#define     SPRITE_PALETTE  ((u16 *)0x05000200)     // Sprite color table 	

	SPRITE_PALETTE[0] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[1] = RGB8( 255, 255, 255 );
	SPRITE_PALETTE[2] = RGB8( 218, 218, 218 );
	SPRITE_PALETTE[3] = RGB8( 182, 182, 182 );
	SPRITE_PALETTE[4] = RGB8( 109, 109, 109 );
	SPRITE_PALETTE[5] = RGB8( 72, 72, 72 );
	SPRITE_PALETTE[6] = RGB8( 36, 36, 36 );
	SPRITE_PALETTE[7] = RGB8( 145, 36, 36 );
	SPRITE_PALETTE[8] = RGB8( 72, 0, 0 );
	SPRITE_PALETTE[9] = RGB8( 182, 145, 72 );
	SPRITE_PALETTE[10] = RGB8( 145, 109, 36 );
	SPRITE_PALETTE[11] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[12] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[13] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[14] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[15] = RGB8( 0, 0, 0 );

	SPRITE_PALETTE[16] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[17] = RGB8( 218, 218, 218 );
	SPRITE_PALETTE[18] = RGB8( 182, 182, 182 );
	SPRITE_PALETTE[19] = RGB8( 145, 145, 145 );
	SPRITE_PALETTE[20] = RGB8( 109, 109, 109 );
	SPRITE_PALETTE[21] = RGB8( 72, 72, 72 );
	SPRITE_PALETTE[22] = RGB8( 36, 36, 36 );
	SPRITE_PALETTE[23] = RGB8( 255, 255, 255 );
	SPRITE_PALETTE[24] = RGB8( 255, 255, 255 );
	SPRITE_PALETTE[25] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[26] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[27] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[28] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[29] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[30] = RGB8( 0, 0, 0 );
	SPRITE_PALETTE[31] = RGB8( 0, 0, 0 );


	//  Copy sprite tile data to safe VRAM (offset by 512 tiles / 0x4000 bytes becase of mode 3
	// in tile mode 0x06010000. in bitmap mode 0x06014000
	//    duh: gba_sprites.h: #define OBJ_BASE_ADR            ((void *)(VRAM + 0x10000))  
	//         gba_sprites.h: #define BITMAP_OBJ_BASE_ADR     ((void *)(VRAM + 0x14000))q
	u16* sprite_vram = (u16*)( 0x06014000);
	//u16* sprite_vram = (u16*)( BITMAP_OBJ_BASE_ADR );
	for(int i = 0; i < 64*9; i++) {
		sprite_vram[i] = sprite_tiles[i];
	}

	// OAM didn't work, use volatial for OAM_MEM
	// gba_sprites.h:#define   OAM                                     ((OBJATTR *)0x07000000)  
	for(int i = 0; i < 128; i++) {
		OAM_MEM[i].attr0 = ATTR0_DISABLED;
	}

	// Configure our single active sprite
	// #define ATTR0_COLOR_16                    (0<<13)
	// #define ATTR0_SQUARE      OBJ_SHAPE(SQUARE)
	// gba_sprites.h:#define OBJ_Y(m)                  ((m)&0x00ff)
	OAM_MEM[0].attr0 = ATTR0_NORMAL | ATTR0_COLOR_16 | ATTR0_SQUARE | OBJ_Y(40); // 4bpp, Square, Y=40


	// gba_sprites.h:#define ATTR1_SIZE_16         (1<<14)
	// gba_sprites.h:#define OBJ_X(m)                  ((m)&0x01ff)
	OAM_MEM[0].attr1 = ATTR1_SIZE_16 | OBJ_X(50);                  // 16x16 size, X=50

	OAM_MEM[0].attr2 = OBJ_CHAR(512) | OBJ_PRIORITY(0);           // Use Tile 512, highest priority


	/// rock
	int rockIndex = 516;
	for( int i=1; i < 9; ++i ){
		OAM_MEM[i].attr0 = ATTR0_NORMAL | ATTR0_COLOR_16 | ATTR0_SQUARE | OBJ_Y(10); // 4bpp, Square, Y=40
		OAM_MEM[i].attr1 = ATTR1_SIZE_16 | OBJ_X(10+i*20);                  // 16x16 size, X=50
		OAM_MEM[i].attr2 = ATTR2_PALETTE(1) | OBJ_CHAR(rockIndex) | OBJ_PRIORITY(0);           // Use Tile 512, highest priority
	}



	int x =50;

	int y =40;
	int tick = 0;
	while (1) {
		VBlankIntrWait();
		/*
		   scanKeys(); 
		   u16 down = keysDownRepeat();
		   if( down & KEY_UP ) y--;
		   if( down & KEY_DOWN) y++;
		   if( down & KEY_LEFT ) x--;
		   if( down & KEY_RIGHT) x++;
		   */
		u32 key = ~(REG_KEYINPUT);

		if(key & KEY_UP)    y--;
		if(key & KEY_DOWN)  y++;
		if(key & KEY_RIGHT) x++;
		if(key & KEY_LEFT)  x--;

		OAM_MEM[0].attr0 &= 0xff00;
		OAM_MEM[0].attr0 |= ( y & 0x00ff );

		OAM_MEM[0].attr1 &= 0xfe00;
		OAM_MEM[0].attr1 |= ( x & 0x00ff );

		tick++;
		if( tick % 10 == 0 ) {
			// update frame
			rockIndex +=4;
			if (rockIndex > 544) rockIndex = 516;
			for( int i=1; i <= 8; ++i ){
				OAM_MEM[i].attr2 &= 0xfc00;
				OAM_MEM[i].attr2 |=  OBJ_CHAR(rockIndex);

			}
		}
	}
}


